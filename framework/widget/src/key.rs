use std::fmt;
use std::hash::{Hash, Hasher};
use std::panic::Location;
use std::sync::atomic::{AtomicU64, Ordering};

use aimer_utils::PanicSite;

/// A stable identity token attached to a [`Widget`](crate::Widget) so the
/// reconciliation algorithm can match old elements to new ones across rebuilds.
///
/// # Constructors
///
/// - [`Key::Value`] equality-based. Two widgets with the same value are
///   considered "the same element". This is the most common key type and covers
///   list-item IDs, tab names, route paths, etc.
/// - [`Key::Object`] identity-based. Matched by pointer/identity, not by
///   value. Use [`Key::unique()`] to generate a key that never matches anything
///   else (useful for forcing a full state reset).
/// - [`Key::Static`] keyed by a static string, which is useful for a key
///   generated by the [`key!`](aimer_macro::key) macro.
/// - [`Key::fixed`] equality-based and allocation-free for externally derived
///   128-bit identities.
/// - **Integers**, converted with `Key::from(7)` or by passing one where
///   `impl Into<Key>` is expected. Equality-based and allocation-free, and equal
///   whatever the integer's width: `Key::from(5u8) == Key::from(5i64)`.
/// - **A tag and an integer**, `Key::from(("user", 7))`. Equality-based and
///   allocation-free, for the common key that says *which kind of thing* and
///   *which one*. The tag must be a `&'static str`.
///
/// A key built from a `&str` or a `String` owns a copy of the text, so it
/// allocates. Where a key is built on every frame or every build, prefer an
/// integer, a tagged integer, or [`Key::Static`].
///
/// Every constructor records its caller in `create_at`. The location is
/// included in [`Debug`] output to make a reconciliation failure point back to
/// the key's creation site, but it never participates in key equality or
/// hashing.
///
/// # Example
///
/// ```rust,ignore
/// use aimer::Key;
///
/// Column::create_new(vec![
///     MyItem::create_new(Some(Key::Value("item-1".into())), ...),
///     MyItem::create_new(Some(Key::Value("item-2".into())), ...),
/// ])
/// ```
#[derive(Clone)]
pub struct Key {
    inner: KeyInner,
    create_at: &'static Location<'static>,
}

impl Key {
    #[inline]
    pub fn with_location(self, location: &'static Location<'static>) -> Self {
        Self {
            inner: self.inner,
            create_at: location,
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
enum KeyInner {
    /// Equality-based key. Two widgets with the same `Value` are "the same".
    Value(String),
    /// Identity-based key. Matched by `ptr::eq` semantics — two `Object` keys
    /// are equal only if they originate from the same [`Key::unique()`] call.
    Object(usize),

    /// Compile-time-based key. Matched by pointer/identity, not by value. use
    /// the `key!` macro to generate a key that can keep the state across
    /// the builds
    Static(&'static str),
    /// Fixed-width equality identity used by portable retained trees.
    Fixed([u8; 16]),
    /// An integer, compared by value whatever its width.
    Number(Number),
    /// A kind of thing and which one of them.
    Tagged(&'static str, Number),
}

/// An integer held by a key.
///
/// Normalized so that every value has exactly one representation: only
/// negative values are `Negative`, every other value is `Unsigned`. That makes
/// the derived equality and hash agree with numeric equality across all the
/// integer widths a key can be made from.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
enum Number {
    Unsigned(u64),
    Negative(i64),
}

impl Number {
    #[inline]
    fn signed(value: i64) -> Self {
        if value < 0 {
            Self::Negative(value)
        } else {
            Self::Unsigned(value as u64)
        }
    }
}

impl fmt::Debug for Key {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter
            .debug_struct("Key")
            .field("inner", &self.inner)
            .field("create_at", &self.create_at)
            .finish()
    }
}

impl PartialEq for Key {
    fn eq(&self, other: &Self) -> bool {
        self.inner == other.inner
    }
}

impl Eq for Key {}

impl Hash for Key {
    #[inline]
    fn hash<H: Hasher>(&self, state: &mut H) {
        match &self.inner {
            KeyInner::Value(s) => {
                state.write_u8(0);
                state.write(s.as_bytes());
            }
            KeyInner::Object(id) => {
                state.write_u8(1);
                state.write_usize(*id);
            }
            KeyInner::Static(s) => {
                state.write_u8(2);
                state.write(s.as_bytes());
            }
            KeyInner::Fixed(value) => {
                state.write_u8(3);
                state.write(value);
            }
            KeyInner::Number(number) => {
                state.write_u8(4);
                number.hash(state);
            }
            KeyInner::Tagged(tag, number) => {
                state.write_u8(5);
                tag.hash(state);
                number.hash(state);
            }
        }
    }
}
/// Ergonomic conversions so callers can pass a bare string literal or `String`
/// wherever a `Key` is expected (e.g. `page_storage::read_or("my-tab", 0)`),
/// producing the common equality-based [`Key::Value`].
impl From<&str> for Key {
    #[track_caller]
    fn from(s: &str) -> Self {
        Self::with_inner(KeyInner::Value(s.to_owned()), Location::caller())
    }
}

impl From<String> for Key {
    #[track_caller]
    fn from(s: String) -> Self {
        Self::with_inner(KeyInner::Value(s), Location::caller())
    }
}

/// Integers convert to a [`Key`] without allocating.
///
/// Keys made from integers of different widths are equal when the numbers are:
/// `Key::from(5u8) == Key::from(5i64)`. A number is never equal to the text of
/// that number.
macro_rules! key_from_integer {
    ($number:expr => $($type:ty),+) => {$(
        impl From<$type> for Key {
            #[inline]
            #[track_caller]
            fn from(value: $type) -> Self {
                let number = ($number)(value);
                Self::with_inner(KeyInner::Number(number), Location::caller())
            }
        }

        /// A tag and an integer make one key, without allocating.
        ///
        /// `("user", 7)` and `("post", 7)` are different keys, and neither is
        /// the key `7`.
        impl From<(&'static str, $type)> for Key {
            #[inline]
            #[track_caller]
            fn from((tag, value): (&'static str, $type)) -> Self {
                let number = ($number)(value);
                Self::with_inner(KeyInner::Tagged(tag, number), Location::caller())
            }
        }
    )+};
}

key_from_integer!(|value| Number::Unsigned(value as u64) => u8, u16, u32, u64, usize);
key_from_integer!(|value| Number::signed(value as i64) => i8, i16, i32, i64, isize);

static UNIQUE_COUNTER: AtomicU64 = AtomicU64::new(0);

impl Key {
    /// Creates an allocation-free equality key from a fixed 128-bit value.
    ///
    /// This constructor is intended for stable identities that already use a
    /// canonical fixed-width representation, such as portable widget IR keys.
    /// Two fixed keys compare equal exactly when all sixteen bytes match. A
    /// fixed key never compares equal to a textual, static, or object key.
    #[inline]
    #[track_caller]
    pub fn fixed(value: [u8; 16]) -> Self {
        Self::with_inner(KeyInner::Fixed(value), Location::caller())
    }

    /// Creates an equality-based key from an owned value.
    #[allow(non_snake_case)]
    #[track_caller]
    pub fn Value(value: String) -> Self {
        Self::with_inner(KeyInner::Value(value), Location::caller())
    }

    /// Creates an identity-based key from a unique identity value.
    #[allow(non_snake_case)]
    #[track_caller]
    pub fn Object(id: usize) -> Self {
        Self::with_inner(KeyInner::Object(id), Location::caller())
    }

    /// Creates a key backed by a compile-time string.
    #[allow(non_snake_case)]
    #[track_caller]
    pub fn Static(value: &'static str) -> Self {
        Self::with_inner(KeyInner::Static(value), Location::caller())
    }

    #[inline]
    fn with_inner(inner: KeyInner, create_at: &'static Location<'static>) -> Self {
        Self { inner, create_at }
    }

    pub(crate) fn diagnostic_description(&self) -> String {
        format!("value {:?}", self.inner)
    }

    pub(crate) fn diagnostic_site(&self) -> PanicSite {
        PanicSite::of(self.create_at)
    }

    /// Generate a globally unique key. Each call returns a key that does not
    /// equal any other key — useful for forcing a state reset on rebuild.
    #[track_caller]
    pub fn unique() -> Self {
        Self::with_inner(
            KeyInner::Object(UNIQUE_COUNTER.fetch_add(1, Ordering::Relaxed) as usize),
            Location::caller(),
        )
    }
}

#[cfg(test)]
mod test {
    use aimer_macro::key;

    use super::*;
    #[test]
    fn test_unique() {
        let key1 = Key::unique();
        let key2 = Key::unique();
        assert_ne!(key1, key2);
    }

    #[test]
    fn test_compile_tile_unique() {
        let key1 = key!();
        let key2 = key!();
        assert_ne!(key1, key2);
    }

    #[test]
    fn debug_includes_creation_location() {
        let key = Key::Value("debug-location".to_owned());
        let debug = format!("{key:?}");

        assert!(debug.contains("create_at"));
        // `Debug` escapes the backslashes of a Windows path.
        assert!(debug.contains(&file!().escape_debug().to_string()));
    }

    #[test]
    fn creation_location_is_not_key_identity() {
        let first = Key::Value("same-value".to_owned());
        let second = Key::Value("same-value".to_owned());

        assert_eq!(first, second);

        let mut first_hash = std::collections::hash_map::DefaultHasher::new();
        first.hash(&mut first_hash);
        let mut second_hash = std::collections::hash_map::DefaultHasher::new();
        second.hash(&mut second_hash);
        assert_eq!(first_hash.finish(), second_hash.finish());
    }

    #[test]
    fn fixed_value_keys_compare_and_hash_without_string_conversion() {
        let first = Key::fixed([0xA5; 16]);
        let second = Key::fixed([0xA5; 16]);
        let different = Key::fixed([0x5A; 16]);

        assert_eq!(first, second);
        assert_ne!(first, different);

        let mut first_hash = std::collections::hash_map::DefaultHasher::new();
        first.hash(&mut first_hash);
        let mut second_hash = std::collections::hash_map::DefaultHasher::new();
        second.hash(&mut second_hash);
        assert_eq!(first_hash.finish(), second_hash.finish());
    }

    #[test]
    fn key_macro_records_the_call_site() {
        let key = key!();
        let debug = format!("{key:?}");

        // `Debug` escapes the backslashes of a Windows path.
        assert!(debug.contains(&file!().escape_debug().to_string()));
    }

    fn hash_of(key: &Key) -> u64 {
        let mut hasher = std::collections::hash_map::DefaultHasher::new();
        key.hash(&mut hasher);
        hasher.finish()
    }

    #[test]
    fn integers_of_every_width_compare_by_value() {
        let keys = [
            Key::from(5u8),
            Key::from(5u16),
            Key::from(5u32),
            Key::from(5u64),
            Key::from(5usize),
            Key::from(5i8),
            Key::from(5i16),
            Key::from(5i32),
            Key::from(5i64),
            Key::from(5isize),
        ];

        for key in &keys {
            assert_eq!(*key, keys[0]);
            assert_eq!(hash_of(key), hash_of(&keys[0]));
        }
        assert_ne!(keys[0], Key::from(6));
    }

    #[test]
    fn negative_and_huge_integers_do_not_collide() {
        assert_eq!(Key::from(-1i8), Key::from(-1i64));
        assert_ne!(Key::from(-1i64), Key::from(u64::MAX));
        assert_ne!(Key::from(i64::MIN), Key::from(0));
        assert_ne!(Key::from(-1), Key::from(1));
        assert_eq!(Key::from(u64::MAX), Key::from(u64::MAX));
    }

    #[test]
    fn a_number_is_not_the_text_of_that_number() {
        assert_ne!(Key::from(5), Key::from("5"));
        assert_ne!(Key::from(5), Key::Static("5"));
        assert_ne!(Key::from(5), Key::Object(5));
    }

    #[test]
    fn a_tag_and_a_number_make_one_key() {
        let key = Key::from(("user", 7));

        assert_eq!(key, Key::from(("user", 7u64)));
        assert_eq!(key, Key::from(("user", 7i8)));
        assert_eq!(hash_of(&key), hash_of(&Key::from(("user", 7u16))));
        assert_ne!(key, Key::from(("user", 8)));
        assert_ne!(key, Key::from(("post", 7)));
        assert_ne!(key, Key::from(7), "the tag is part of the identity");
        assert_ne!(key, Key::Static("user"));
        assert_ne!(key, Key::from("user"));
        assert_ne!(Key::from(("user", -1)), Key::from(("user", u64::MAX)));
    }

    #[test]
    fn a_numeric_key_is_not_a_fixed_key() {
        let mut bytes = [0u8; 16];
        bytes[..8].copy_from_slice(&5u64.to_le_bytes());

        assert_ne!(Key::from(5u64), Key::fixed(bytes));
    }
}
