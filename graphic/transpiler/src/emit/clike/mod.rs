//! C-like emitter shared by Metal Shading Language and HLSL.
//!
//! The statement and expression lowering follows `emit::wgsl`: `emit_expr` returns pure expression
//! text and pushes the statements it needs first, `emit_into` writes a value to a destination.
//! This file holds the declarations: structs, resources, constant tables, function order, entry points.
//!
//! What C-like targets need that WGSL does not:
//! - declaration before use, so structs and functions are written in dependency order;
//! - MSL has no global resources, so every function gets the resources it (transitively) reads as
//!   hidden parameters;
//! - MSL allows one `[[stage_in]]` struct, so several `#[input]` structs are merged into one.

mod dialect;
mod expr;
mod glsl;
mod stmt;

use std::collections::{HashMap, HashSet};

use super::common::{Dest, assign_locations, int_text, mark};
use crate::ast::*;
use crate::error::{Result, bail};
use crate::resolve::{Program, Stage, bind_args};
use crate::sema::{Env, Globals, Ty};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Dialect {
    Msl,
    Hlsl,
    Glsl,
}

pub use glsl::{GlslOutput, emit_glsl};

pub fn emit(p: &Program, d: Dialect) -> Result<String> {
    em_new(p, d).run()
}

fn em_new(p: &Program, d: Dialect) -> Emitter<'_> {
    Emitter {
        d,
        p,
        g: &p.globals,
        env: Env::new(),
        lines: Vec::new(),
        indent: 0,
        tmp: 0,
        loops: Vec::new(),
        ret: Ty::Unit,
        locations: HashMap::new(),
        resources: Vec::new(),
        uses: HashMap::new(),
        tables: Vec::new(),
        merged_inputs: false,
        needs_texture_size: false,
        es: false,
        stage: None,
        glsl_pairs: Vec::new(),
        glsl_rem: Vec::new(),
        glsl_specs: Vec::new(),
        glsl_alias: HashMap::new(),
        glsl_spec_name: None,
    }
}

/// GLSL: a copy of a function that takes textures or samplers, with those parameters fixed to globals.
#[derive(Clone)]
struct GlslSpec {
    fn_name: String,
    /// parameter name, global resource it is bound to
    binds: Vec<(String, String)>,
    emitted: String,
}

struct Resource {
    name: String,
    kind: ResourceKind,
    group: u32,
    binding: u32,
}

struct Emitter<'a> {
    d: Dialect,
    p: &'a Program,
    g: &'a Globals,
    env: Env,
    lines: Vec<String>,
    indent: usize,
    tmp: usize,
    /// One entry per enclosing loop: where `break value` goes, if the loop is a value.
    loops: Vec<Option<Dest>>,
    ret: Ty,
    /// struct name -> location of each field (None for builtins and plain fields).
    locations: HashMap<String, Vec<Option<u32>>>,
    /// Every resource, in declaration order.
    resources: Vec<Resource>,
    /// function name -> resources it reads, directly or through callees (MSL threads these).
    uses: HashMap<String, Vec<String>>,
    /// const arrays that are written as a global table.
    tables: Vec<String>,
    /// MSL with several `#[input]` structs on the vertex entry.
    merged_inputs: bool,
    /// HLSL: the `size()` helper is needed.
    needs_texture_size: bool,
    /// GLSL: target GLSL ES 3.00 instead of GLSL 3.30 core.
    es: bool,
    /// GLSL: the stage being written.
    stage: Option<Stage>,
    /// GLSL: texture and sampler pairs fused into one `sampler2D`, in first-use order.
    glsl_pairs: Vec<(String, Option<String>)>,
    /// GLSL: `%` on these floating point types needs a helper.
    glsl_rem: Vec<String>,
    /// GLSL: specialised copies of functions with texture or sampler parameters, in request order.
    glsl_specs: Vec<GlslSpec>,
    /// GLSL: while writing a specialised copy, parameter name -> the global it stands for.
    glsl_alias: HashMap<String, String>,
    /// GLSL: the name the function being written gets, when it is a specialised copy.
    glsl_spec_name: Option<String>,
}

impl<'a> Emitter<'a> {
    fn id(&self, s: &str) -> String {
        dialect::ident(self.d, s)
    }

    fn run(&mut self) -> Result<String> {
        self.locations = assign_locations(self.p, self.g)?;
        self.collect_resources()?;
        self.collect_uses();
        self.merged_inputs = self.d == Dialect::Msl && self.vertex_input_structs().len() > 1;

        let mut chunks: Vec<String> = Vec::new();
        chunks.push(format!("// Generated by aimer_transpiler from `{}.aimer`. Do not edit.", self.p.name));
        if self.d == Dialect::Msl {
            chunks.push("#include <metal_stdlib>\n\nusing namespace metal;".into());
        }

        for it in self.struct_order() {
            let ItemKind::Struct { name, fields, .. } = &it.kind else { unreachable!() };
            let text = self.emit_struct(it, name, fields).map_err(|e| e.context(format!("struct `{name}`")))?;
            if !self.p.external.contains(name) {
                chunks.push(text);
            }
        }
        if self.d == Dialect::Hlsl {
            let mut decls = Vec::new();
            for r in &self.resources {
                if !self.p.external.contains(&r.name) {
                    decls.push(self.hlsl_resource(r)?);
                }
            }
            if !decls.is_empty() {
                chunks.push(decls.join("\n"));
            }
        }
        for n in self.tables.clone() {
            chunks.push(self.emit_table(&n).map_err(|e| e.context(format!("const `{n}`")))?);
        }

        let mut fns = Vec::new();
        for it in self.fn_order() {
            let ItemKind::Fn { name, .. } = &it.kind else { unreachable!() };
            // External functions are still emitted once so that their bodies are type checked.
            let text = self.emit_fn(it).map_err(|e| e.context(format!("in fn `{name}`")))?;
            if !self.p.external.contains(name) {
                fns.push(text);
            }
        }
        if self.needs_texture_size {
            chunks.push(
                "uint2 _aimer_texture_size(Texture2D<float4> t) {\n    uint w;\n    uint h;\n    t.GetDimensions(w, h);\n    return uint2(w, h);\n}"
                    .into(),
            );
        }
        chunks.extend(fns);
        Ok(chunks.join("\n\n") + "\n")
    }

    // ---- analysis ----

    fn collect_resources(&mut self) -> Result<()> {
        for it in &self.p.items {
            if let ItemKind::Resource { kind, name, .. } = &it.kind {
                let (group, binding) = bind_args(it).map_err(|e| e.context(format!("resource `{name}`")))?;
                self.resources.push(Resource { name: name.clone(), kind: *kind, group, binding });
            }
        }
        Ok(())
    }

    /// Which resources each function reads, and which const arrays need a table.
    fn collect_uses(&mut self) {
        let res_names: HashSet<&str> = self.resources.iter().map(|r| r.name.as_str()).collect();
        let mut direct: HashMap<String, HashSet<String>> = HashMap::new();
        let mut callees: HashMap<String, Vec<String>> = HashMap::new();
        let mut tables: Vec<String> = Vec::new();
        for it in &self.p.items {
            let ItemKind::Fn { name, body, .. } = &it.kind else { continue };
            let d = direct.entry(name.clone()).or_default();
            let c = callees.entry(name.clone()).or_default();
            walk_block(body, &mut |e| match e {
                Expr::Path(n) if res_names.contains(n.as_str()) => {
                    d.insert(n.clone());
                }
                Expr::Path(n) if self.g.consts.get(n).is_some_and(|k| matches!(k.ty, Ty::Array(..))) => {
                    if !tables.contains(n) {
                        tables.push(n.clone());
                    }
                }
                Expr::Call { name: callee, .. } if self.g.fns.contains_key(callee) => c.push(callee.clone()),
                _ => {}
            });
        }
        loop {
            let mut changed = false;
            for (f, cs) in &callees {
                for c in cs {
                    let extra: Vec<String> = direct.get(c).map(|s| s.iter().cloned().collect()).unwrap_or_default();
                    let mine = direct.get_mut(f).expect("fn");
                    for r in extra {
                        changed |= mine.insert(r);
                    }
                }
            }
            if !changed {
                break;
            }
        }
        for (f, set) in direct {
            let ordered = self.resources.iter().filter(|r| set.contains(&r.name)).map(|r| r.name.clone()).collect();
            self.uses.insert(f, ordered);
        }
        self.tables = tables;
    }

    fn vertex_input_structs(&self) -> Vec<String> {
        let mut out = Vec::new();
        if let Some(Item { kind: ItemKind::Fn { params, .. }, .. }) = self.p.entry(Stage::Vertex) {
            for prm in params {
                if let Ok(Ty::Struct(s)) = self.g.resolve_type(&prm.ty) {
                    if self.struct_item(&s).is_some_and(|i| i.attr("input").is_some()) {
                        out.push(s);
                    }
                }
            }
        }
        out
    }

    fn struct_item(&self, name: &str) -> Option<&'a Item> {
        self.p.items.iter().find(|i| matches!(&i.kind, ItemKind::Struct { name: n, .. } if n == name))
    }

    /// Structs after the structs they contain: C needs the definition before the use.
    fn struct_order(&self) -> Vec<&'a Item> {
        fn visit<'a>(em: &Emitter<'a>, it: &'a Item, seen: &mut HashSet<String>, out: &mut Vec<&'a Item>) {
            let ItemKind::Struct { name, fields, .. } = &it.kind else { return };
            if !seen.insert(name.clone()) {
                return;
            }
            for f in fields {
                let mut t = em.g.resolve_type(&f.ty).ok();
                while let Some(Ty::Array(e, _)) = t {
                    t = Some(*e);
                }
                if let Some(Ty::Struct(s)) = t {
                    if let Some(dep) = em.struct_item(&s) {
                        visit(em, dep, seen, out);
                    }
                }
            }
            out.push(it);
        }
        let mut seen = HashSet::new();
        let mut out = Vec::new();
        for it in &self.p.items {
            visit(self, it, &mut seen, &mut out);
        }
        out
    }

    /// Functions after the functions they call.
    fn fn_order(&self) -> Vec<&'a Item> {
        fn visit<'a>(p: &'a Program, it: &'a Item, seen: &mut HashSet<String>, out: &mut Vec<&'a Item>) {
            let ItemKind::Fn { name, body, .. } = &it.kind else { return };
            if !seen.insert(name.clone()) {
                return;
            }
            let mut callees: Vec<String> = Vec::new();
            walk_block(body, &mut |e| {
                if let Expr::Call { name, .. } = e {
                    callees.push(name.clone());
                }
            });
            for c in callees {
                if let Some(dep) = p.items.iter().find(|i| matches!(&i.kind, ItemKind::Fn { name: n, .. } if *n == c)) {
                    visit(p, dep, seen, out);
                }
            }
            out.push(it);
        }
        let mut seen = HashSet::new();
        let mut out = Vec::new();
        for it in &self.p.items {
            visit(self.p, it, &mut seen, &mut out);
        }
        out
    }

    // ---- types ----

    fn array_size(&self, n: &Expr) -> Result<String> {
        match n {
            Expr::Int(s) => Ok(int_text(s).trim_end_matches('u').to_string()),
            other => match self.g.const_int(other) {
                Some(v) => Ok(v.to_string()),
                None => bail!("array size must be a compile-time integer, found {other:?}"),
            },
        }
    }

    fn ty_text(&self, t: &Ty) -> Result<String> {
        if matches!(t, Ty::Mat(_)) && self.d == Dialect::Hlsl {
            bail!("matrices are not supported by the HLSL emitter yet");
        }
        if self.d == Dialect::Glsl && matches!(t, Ty::Texture | Ty::Sampler) {
            bail!("GLSL has no separate texture or sampler types: use them only as globals with `.sample(..)`, `.load(..)` and `.size()`");
        }
        if matches!(t, Ty::Array(e, _) if matches!(**e, Ty::Array(..))) && self.d == Dialect::Glsl {
            bail!("arrays of arrays are not available in GLSL 3.30 and GLSL ES 3.00");
        }
        if let Some(s) = dialect::scalar_like_text(self.d, t) {
            return Ok(s);
        }
        match t {
            Ty::Struct(n) => Ok(self.id(n)),
            Ty::Array(..) => bail!("array types can only be used for variables, fields and tables"),
            Ty::Unit | Ty::Never => bail!("`{}` has no {} type", t.describe(), self.target_name()),
            _ => unreachable!(),
        }
    }

    fn target_name(&self) -> &'static str {
        match self.d {
            Dialect::Msl => "MSL",
            Dialect::Hlsl => "HLSL",
            Dialect::Glsl => "GLSL",
        }
    }

    /// `float2 name` or, for arrays, `float2 name[6]`.
    fn decl(&self, ty: &Ty, name: &str) -> Result<String> {
        let mut dims = String::new();
        let mut t = ty;
        while let Ty::Array(e, n) = t {
            dims.push_str(&format!("[{}]", self.array_size(n)?));
            t = e;
        }
        Ok(format!("{} {name}{dims}", self.ty_text(t)?))
    }

    /// The value a `let mut x: T;` starts with.
    fn zero_init(&self, ty: &Ty) -> Result<String> {
        Ok(match ty {
            Ty::Scalar(crate::sema::Scalar::F32) => "0.0".into(),
            Ty::Scalar(crate::sema::Scalar::I32) => "0".into(),
            Ty::Scalar(crate::sema::Scalar::U32) => "0u".into(),
            Ty::Scalar(crate::sema::Scalar::Bool) => "false".into(),
            Ty::Vec(..) | Ty::Mat(_) if self.d == Dialect::Hlsl => format!("(({})0)", self.ty_text(ty)?),
            Ty::Vec(..) | Ty::Mat(_) => format!("{}(0)", self.ty_text(ty)?),
            Ty::Struct(n) => match self.d {
                Dialect::Msl => format!("{}{{}}", self.id(n)),
                Dialect::Hlsl => format!("({})0", self.id(n)),
                Dialect::Glsl => {
                    let mut parts = Vec::new();
                    for f in &self.g.structs[n] {
                        parts.push(self.zero_init(&self.g.resolve_type(&f.ty)?)?);
                    }
                    format!("{}({})", self.id(n), parts.join(", "))
                }
            },
            Ty::Array(e, n) if self.d == Dialect::Glsl => {
                let z = self.zero_init(e)?;
                let n = self.array_size(n)?;
                let count: usize = n.parse().unwrap_or(1);
                format!("{}[{n}]({})", self.ty_text(e)?, vec![z; count].join(", "))
            }
            Ty::Array(..) => match self.d {
                Dialect::Msl => "{}".into(),
                Dialect::Glsl => unreachable!(),
                Dialect::Hlsl => {
                    let mut dims = String::new();
                    let mut t = ty;
                    while let Ty::Array(e, n) = t {
                        dims.push_str(&format!("[{}]", self.array_size(n)?));
                        t = e;
                    }
                    format!("({}{dims})0", self.ty_text(t)?)
                }
            },
            _ => bail!("`{}` cannot be declared without a value", ty.describe()),
        })
    }

    // ---- structs, resources, tables ----

    fn emit_struct(&self, it: &Item, name: &str, fields: &[Field]) -> Result<String> {
        let locs = &self.locations[name];
        let is_input = it.attr("input").is_some();
        let is_varying = it.attr("varying").is_some();
        let mut out = format!("struct {} {{\n", self.id(name));
        for (f, loc) in fields.iter().zip(locs) {
            for m in &f.marks {
                if !matches!(m.name.as_str(), "position" | "flat" | "location") {
                    bail!("field `{}`: unknown marker `@{}`", f.name, m.name);
                }
            }
            let ty = self.g.resolve_type(&f.ty)?;
            let mut decl = self.decl(&ty, &self.id(&f.name))?;
            let flat = mark(f, "flat").is_some();
            let position = mark(f, "position").is_some();
            let loc = if is_input || is_varying { *loc } else { None };
            let suffix = match self.d {
                Dialect::Msl => {
                    if position {
                        " [[position]]".to_string()
                    } else if let (true, false, Some(l)) = (is_input, self.merged_inputs, loc) {
                        format!(" [[attribute({l})]]")
                    } else if let (true, Some(l)) = (is_varying, loc) {
                        if flat { format!(" [[user(loc{l}), flat]]") } else { format!(" [[user(loc{l})]]") }
                    } else {
                        String::new()
                    }
                }
                Dialect::Glsl => String::new(),
                Dialect::Hlsl => {
                    if position {
                        " : SV_Position".to_string()
                    } else if let Some(l) = loc {
                        if flat {
                            decl = format!("nointerpolation {decl}");
                        }
                        format!(" : TEXCOORD{l}")
                    } else {
                        String::new()
                    }
                }
            };
            out.push_str(&format!("    {decl}{suffix};\n"));
        }
        out.push_str("};");
        Ok(out)
    }

    fn hlsl_resource(&self, r: &Resource) -> Result<String> {
        let name = self.id(&r.name);
        let (g, b) = (r.group, r.binding);
        Ok(match r.kind {
            ResourceKind::Uniform => {
                let ty = self.ty_text(&self.g.resources[&r.name])?;
                format!("ConstantBuffer<{ty}> {name} : register(b{b}, space{g});")
            }
            ResourceKind::Texture => format!("Texture2D<float4> {name} : register(t{b}, space{g});"),
            ResourceKind::Sampler => format!("SamplerState {name} : register(s{b}, space{g});"),
        })
    }

    /// MSL parameter for a resource. Entry points also say where it is bound.
    fn msl_resource_param(&self, r: &Resource, bound: bool) -> Result<String> {
        let name = self.id(&r.name);
        let slot = r.group * 4 + r.binding;
        Ok(match r.kind {
            ResourceKind::Uniform => {
                let ty = self.ty_text(&self.g.resources[&r.name])?;
                let at = if bound { format!(" [[buffer({slot})]]") } else { String::new() };
                format!("constant {ty}& {name}{at}")
            }
            ResourceKind::Texture => {
                let at = if bound { format!(" [[texture({slot})]]") } else { String::new() };
                format!("texture2d<float> {name}{at}")
            }
            ResourceKind::Sampler => {
                let at = if bound { format!(" [[sampler({slot})]]") } else { String::new() };
                format!("sampler {name}{at}")
            }
        })
    }

    fn emit_table(&mut self, n: &str) -> Result<String> {
        let c = self.g.consts[n].clone();
        let Expr::ArrayLit(items) = &c.value else { bail!("a const array must be an array literal") };
        let saved = std::mem::replace(&mut self.env, Env::new());
        let r = (|| -> Result<String> {
            let mut body = String::new();
            for it in items {
                let (t, lines) = self.capture(|s| s.emit_expr(it))?;
                if !lines.is_empty() || t.is_empty() {
                    bail!("table elements must be plain expressions");
                }
                body.push_str(&format!("    {t},\n"));
            }
            let decl = self.decl(&c.ty, &self.id(n))?;
            let prefix = match self.d {
                Dialect::Msl => "constant",
                Dialect::Hlsl => "static const",
                Dialect::Glsl => "const",
            };
            if self.d == Dialect::Glsl {
                let Ty::Array(e, n) = &c.ty else { unreachable!() };
                let body = body.trim_end().trim_end_matches(',').to_string();
                let items: Vec<&str> = body.lines().map(str::trim).collect();
                let items: Vec<String> = items.iter().map(|l| l.trim_end_matches(',').to_string()).collect();
                return Ok(format!("{prefix} {decl} = {}[{}](\n    {}\n);", self.ty_text(e)?, self.array_size(n)?, items.join(",\n    ")));
            }
            Ok(format!("{prefix} {decl} = {{\n{body}}};"))
        })();
        self.env = saved;
        r
    }

    // ---- functions ----

    fn emit_fn(&mut self, it: &Item) -> Result<String> {
        let ItemKind::Fn { name, params, ret, body } = &it.kind else { unreachable!() };
        self.env = Env::new();
        self.lines.clear();
        self.indent = 1;
        self.tmp = 0;
        self.loops.clear();
        // Resources and tables are globals (HLSL) or parameters (MSL): no local may take their names.
        let reserved: Vec<String> = self.resources.iter().map(|r| r.name.clone()).chain(self.tables.iter().cloned()).collect();
        for n in reserved {
            let n = self.id(&n);
            self.env.declare_hidden(&n);
        }
        let stage = if it.attr("vertex").is_some() {
            Some(Stage::Vertex)
        } else if it.attr("fragment").is_some() {
            Some(Stage::Fragment)
        } else {
            None
        };

        let mut param_texts = Vec::new();
        let mut merged: Vec<(String, String, String)> = Vec::new(); // (param name, struct name, source param name)
        for prm in params {
            let ty = self.g.resolve_type(&prm.ty)?;
            let emitted = self.declare_local(&prm.name, ty.clone(), false);
            // GLSL has no texture or sampler parameters: the specialised copy bakes the global in.
            if self.d == Dialect::Glsl && matches!(ty, Ty::Texture | Ty::Sampler) {
                continue;
            }
            let text = match &prm.ty {
                Type::Builtin(b) => {
                    if stage.is_none() {
                        bail!("builtin type `@{b}` is only valid on entry-point parameters");
                    }
                    let (msl, hlsl, cty) = match b.as_str() {
                        "vertex_index" => ("[[vertex_id]]", ": SV_VertexID", "uint"),
                        "instance_index" => ("[[instance_id]]", ": SV_InstanceID", "uint"),
                        "frag_coord" => ("[[position]]", ": SV_Position", "float4"),
                        _ => bail!("`@{b}` cannot be an entry-point parameter"),
                    };
                    match self.d {
                        Dialect::Msl => format!("{cty} {emitted} {msl}"),
                        Dialect::Hlsl => format!("{cty} {emitted} {hlsl}"),
                        Dialect::Glsl => format!("{} {emitted}", if cty == "float4" { "vec4" } else { cty }),
                    }
                }
                _ => match (&ty, stage) {
                    (Ty::Struct(s), Some(_)) if self.d == Dialect::Msl => {
                        if self.merged_inputs && self.struct_item(s).is_some_and(|i| i.attr("input").is_some()) {
                            merged.push((emitted.clone(), s.clone(), prm.name.clone()));
                            continue;
                        }
                        format!("{} {emitted} [[stage_in]]", self.id(s))
                    }
                    _ => self.decl(&ty, &emitted)?,
                },
            };
            param_texts.push(text);
        }

        // Several `#[input]` structs share one `[[stage_in]]` struct in MSL.
        let mut preface = String::new();
        let mut prologue: Vec<String> = Vec::new();
        if !merged.is_empty() {
            let entry = self.id(name);
            let sname = format!("{entry}_inputs");
            let var = self.alloc_name("inputs");
            let mut s = format!("struct {sname} {{\n");
            for (pn, st, src) in &merged {
                let ItemKind::Struct { fields, .. } = &self.struct_item(st).expect("struct").kind else { unreachable!() };
                let locs = &self.locations[st];
                for (f, loc) in fields.iter().zip(locs) {
                    let ty = self.g.resolve_type(&f.ty)?;
                    let decl = self.decl(&ty, &format!("{src}_{}", self.id(&f.name)))?;
                    match loc {
                        Some(l) => s.push_str(&format!("    {decl} [[attribute({l})]];\n")),
                        None => s.push_str(&format!("    {decl};\n")),
                    }
                    prologue.push(format!("    {pn}.{0} = {var}.{src}_{0};", self.id(&f.name)));
                }
            }
            s.push_str("};");
            preface = format!("{s}\n\n");
            let mut decls = Vec::new();
            for (pn, st, _) in &merged {
                decls.push(format!("    {} {pn};", self.id(st)));
            }
            decls.extend(prologue);
            prologue = decls;
            param_texts.insert(0, format!("{sname} {var} [[stage_in]]"));
        }

        let ret_ty = match ret {
            Some(r) => self.g.resolve_type(r)?,
            None => Ty::Unit,
        };
        let ret_text = match (ret, &ret_ty) {
            (_, Ty::Unit) => "void".to_string(),
            (Some(Type::Builtin(b)), _) => {
                if b != "frag_color" {
                    bail!("`@{b}` cannot be a return type");
                }
                if self.d == Dialect::Glsl { "vec4" } else { "float4" }.to_string()
            }
            (_, t) => self.ty_text(t)?,
        };
        if stage == Some(Stage::Vertex) {
            let ok = match &ret_ty {
                Ty::Struct(s) => self.g.structs[s].iter().any(|f| mark(f, "position").is_some()),
                _ => false,
            };
            if !ok {
                bail!("a `#[vertex]` function must return a `#[varying]` struct with an `@position` field");
            }
        }
        self.ret = ret_ty.clone();

        // The body must have the declared type.
        let body_ty = {
            let mut check = self.env.clone();
            self.g.type_of_block_inner(&mut check, body)?
        };
        if body_ty != ret_ty && body_ty != Ty::Never {
            let hint = if body_ty == Ty::Unit && ret_ty != Ty::Unit {
                " (does the last expression end with `;`? remove it to return the value)"
            } else {
                ""
            };
            bail!("the body has type {}, but the function returns {}{hint}", body_ty.describe(), ret_ty.describe());
        }

        let mut suffix = String::new();
        if self.d == Dialect::Msl {
            let needed = self.uses.get(name).cloned().unwrap_or_default();
            for r in &needed {
                let res = self.resources.iter().find(|x| &x.name == r).expect("resource");
                param_texts.push(self.msl_resource_param(res, stage.is_some())?);
            }
        }
        if self.d == Dialect::Hlsl && matches!(ret, Some(Type::Builtin(_))) {
            suffix = " : SV_Target0".into();
        }
        let prefix = match (self.d, stage) {
            (Dialect::Msl, Some(Stage::Vertex)) => "vertex ",
            (Dialect::Msl, Some(Stage::Fragment)) => "fragment ",
            // A function-only shader is a library: its helpers are meant to be unused in the file.
            (Dialect::Msl, None) if self.p.entry(Stage::Vertex).is_none() && self.p.entry(Stage::Fragment).is_none() => {
                "[[maybe_unused]] static "
            }
            (Dialect::Msl, None) => "static ",
            _ => "",
        };

        self.emit_block(body, &Dest::Return, false)?;
        let body_lines = std::mem::take(&mut self.lines);

        let mut out = preface;
        let fn_name = self.glsl_spec_name.clone().unwrap_or_else(|| self.id(name));
        out.push_str(&format!("{prefix}{ret_text} {fn_name}({}){suffix} {{\n", param_texts.join(", ")));
        for l in prologue {
            out.push_str(&l);
            out.push('\n');
        }
        for l in body_lines {
            out.push_str(&l);
            out.push('\n');
        }
        out.push('}');
        Ok(out)
    }
}
