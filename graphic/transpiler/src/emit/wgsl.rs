//! WGSL emitter.
//!
//! The source language is expression-oriented, WGSL is statement-oriented. Every expression is
//! lowered with `emit_expr` (returns the text of a pure WGSL expression, pushing any statements it
//! needs first) or `emit_into` (writes the value to a destination: discard, return, or a variable).

