/// Source name to WGSL name: reserved words and `__x` names are not legal identifiers.
fn ident(s: &str) -> String {
    if RESERVED.contains(&s) {
        format!("{s}_")
    } else if s == "_" || s.starts_with("__") {
        format!("v{s}")
    } else {
        s.to_string()
    }
}


pub fn emit(p: &Program) -> Result<String> {
    let mut em = Emitter {
        p,
        g: &p.globals,
        env: Env::new(),
        lines: Vec::new(),
        indent: 0,
        tmp: 0,
        loops: Vec::new(),
        ret: Ty::Unit,
        tables: HashMap::new(),
        tables_used: Vec::new(),
        locations: HashMap::new(),
        f32_literals: 0,
    };
    em.run()
}

struct Emitter<'a> {
    p: &'a Program,
    g: &'a Globals,
    env: Env,
    lines: Vec<String>,
    indent: usize,
    tmp: usize,
    /// One entry per enclosing loop: where `break value` goes, if the loop is a value.
    loops: Vec<Option<Dest>>,
    ret: Ty,
    /// const array name -> local variable name, for the current function.
    tables: HashMap<String, String>,
    tables_used: Vec<String>,
    /// struct name -> location of each field (None for builtins and plain fields).
    locations: HashMap<String, Vec<Option<u32>>>,
    /// > 0 while emitting the value of an inlined const that contains arithmetic. Float literals
    /// are then written as `f32(..)`, so WGSL evaluates the maths in f32 and not in abstract floats.
    f32_literals: usize,
}

impl<'a> Emitter<'a> {
    fn run(&mut self) -> Result<String> {
        self.locations = common::assign_locations(self.p, self.g)?;
        let mut chunks: Vec<String> = Vec::new();
        chunks.push(format!("// Generated by aimer_transpiler from `{}.aimer`. Do not edit.", self.p.name));

        let mut resources = Vec::new();
        for it in &self.p.items {
            if let ItemKind::Resource { kind, name, .. } = &it.kind {
                if self.p.external.contains(name) {
                    continue;
                }
                let (group, binding) = bind_args(it).map_err(|e| e.context(format!("resource `{name}`")))?;
                let ty = self.ty_text(&self.g.resources[name].clone())?;
                let var = match kind {
                    ResourceKind::Uniform => "var<uniform>",
                    _ => "var",
                };
                resources.push(format!("@group({group}) @binding({binding})\n{var} {}: {ty};", ident(name)));
            }
        }
        if !resources.is_empty() {
            chunks.push(resources.join("\n\n"));
        }

        for it in &self.p.items {
            if let ItemKind::Struct { name, fields, .. } = &it.kind {
                let text = self.emit_struct(it, name, fields).map_err(|e| e.context(format!("struct `{name}`")))?;
                if !self.p.external.contains(name) {
                    chunks.push(text);
                }
            }
        }
        for it in &self.p.items {
            if let ItemKind::Fn { name, .. } = &it.kind {
                // External functions are still emitted once so that their bodies are type checked.
                let text = self.emit_fn(it).map_err(|e| e.context(format!("in fn `{name}`")))?;
                if !self.p.external.contains(name) {
                    chunks.push(text);
                }
            }
        }
        Ok(chunks.join("\n\n") + "\n")
    }

    // ---- structs and locations ----

    fn mark<'f>(f: &'f Field, name: &str) -> Option<&'f Mark> {
        common::mark(f, name)
    }

    fn emit_struct(&self, _it: &Item, name: &str, fields: &[Field]) -> Result<String> {
        let locs = &self.locations[name];
        let mut out = format!("struct {} {{\n", ident(name));
        for (f, loc) in fields.iter().zip(locs) {
            let mut attrs: Vec<String> = Vec::new();
            if Self::mark(f, "position").is_some() {
                attrs.push("@builtin(position)".into());
            }
            if let Some(l) = loc {
                attrs.push(format!("@location({l})"));
            }
            if Self::mark(f, "flat").is_some() {
                attrs.push("@interpolate(flat)".into());
            }
            for m in &f.marks {
                if !matches!(m.name.as_str(), "position" | "flat" | "location") {
                    bail!("field `{}`: unknown marker `@{}`", f.name, m.name);
                }
            }
            let ty = self.ty_text(&self.g.resolve_type(&f.ty)?)?;
            let prefix = if attrs.is_empty() { String::new() } else { format!("{} ", attrs.join(" ")) };
            out.push_str(&format!("    {prefix}{}: {ty},\n", ident(&f.name)));
        }
        out.push('}');
        Ok(out)
    }

    fn ty_text(&self, t: &Ty) -> Result<String> {
        Ok(match t {
            Ty::Scalar(s) => s.name().to_string(),
            Ty::Vec(n, s) => format!("vec{n}<{}>", s.name()),
            Ty::Mat(n) => format!("mat{n}x{n}<f32>"),
            Ty::Array(e, n) => {
                let size = match &**n {
                    Expr::Int(s) => int_text(s),
                    other => bail!("array size must be a compile-time integer, found {other:?}"),
                };
                format!("array<{}, {size}>", self.ty_text(e)?)
            }
            Ty::Struct(n) => ident(n),
            Ty::Texture => "texture_2d<f32>".into(),
            Ty::Sampler => "sampler".into(),
            Ty::Unit | Ty::Never => bail!("`{}` has no WGSL type", t.describe()),
        })
    }

    // ---- functions ----

    fn emit_fn(&mut self, it: &Item) -> Result<String> {
        let ItemKind::Fn { name, params, ret, body } = &it.kind else { unreachable!() };
        self.env = Env::new();
        self.lines.clear();
        self.indent = 1;
        self.tmp = 0;
        self.loops.clear();
        self.tables.clear();
        self.tables_used.clear();
        let stage = if it.attr("vertex").is_some() {
            Some("vertex")
        } else if it.attr("fragment").is_some() {
            Some("fragment")
        } else {
            None
        };

        let mut param_texts = Vec::new();
        for prm in params {
            let ty = self.g.resolve_type(&prm.ty)?;
            let emitted = self.declare_local(&prm.name, ty.clone(), false);
            let attr = match &prm.ty {
                Type::Builtin(b) => {
                    if stage.is_none() {
                        bail!("builtin type `@{b}` is only valid on entry-point parameters");
                    }
                    match b.as_str() {
                        "vertex_index" => "@builtin(vertex_index) ",
                        "instance_index" => "@builtin(instance_index) ",
                        "frag_coord" => "@builtin(position) ",
                        _ => bail!("`@{b}` cannot be an entry-point parameter"),
                    }
                }
                _ => "",
            };
            param_texts.push(format!("{attr}{emitted}: {}", self.ty_text(&ty)?));
        }
        let ret_ty = match ret {
            Some(r) => self.g.resolve_type(r)?,
            None => Ty::Unit,
        };
        let ret_text = match (ret, &ret_ty) {
            (_, Ty::Unit) => String::new(),
            (Some(Type::Builtin(b)), t) => {
                if b != "frag_color" {
                    bail!("`@{b}` cannot be a return type");
                }
                format!(" -> @location(0) {}", self.ty_text(t)?)
            }
            (_, t) => format!(" -> {}", self.ty_text(t)?),
        };
        if stage == Some("vertex") {
            let ok = match &ret_ty {
                Ty::Struct(s) => self.g.structs[s].iter().any(|f| Self::mark(f, "position").is_some()),
                _ => false,
            };
            if !ok {
                bail!("a `#[vertex]` function must return a `#[varying]` struct with an `@position` field");
            }
        }
        self.ret = ret_ty.clone();

        // The body must have the declared type.
        let body_ty = {
            let mut check = self.env.clone();
            self.g.type_of_block_inner(&mut check, body)?
        };
        if body_ty != ret_ty && body_ty != Ty::Never {
            let hint = if body_ty == Ty::Unit && ret_ty != Ty::Unit {
                " (does the last expression end with `;`? remove it to return the value)"
            } else {
                ""
            };
            bail!("the body has type {}, but the function returns {}{hint}", body_ty.describe(), ret_ty.describe());
        }

        // Tables for runtime-indexed const arrays get a local name that cannot clash with locals.
        let mut table_consts: Vec<String> = Vec::new();
        walk_block(body, &mut |e| {
            if let Expr::Path(n) = e {
                if let Some(c) = self.g.consts.get(n) {
                    if matches!(c.ty, Ty::Array(..)) && !table_consts.contains(n) {
                        table_consts.push(n.clone());
                    }
                }
            }
        });
        for n in table_consts {
            let local = self.alloc_name(&n.to_lowercase());
            self.tables.insert(n, local);
        }

        self.emit_block(body, &Dest::Return, false)?;
        let body_lines = std::mem::take(&mut self.lines);

        let mut out = String::new();
        if let Some(s) = stage {
            out.push_str(&format!("@{s}\n"));
        }
        out.push_str(&format!("fn {}({}){ret_text} {{\n", ident(name), param_texts.join(", ")));
        for n in self.tables_used.clone() {
            out.push_str(&self.table_decl(&n)?);
        }
        for l in body_lines {
            out.push_str(&l);
            out.push('\n');
        }
        out.push('}');
        Ok(out)
    }

    fn table_decl(&mut self, n: &str) -> Result<String> {
        let c = self.g.consts[n].clone();
        let local = self.tables[n].clone();
        let ty = self.ty_text(&c.ty)?;
        let saved = std::mem::replace(&mut self.env, Env::new());
        let r = (|| -> Result<String> {
            match &c.value {
                Expr::ArrayLit(items) => {
                    let mut s = format!("    var {local} = {ty}(\n");
                    for it in items {
                        let wrap = has_arithmetic(it);
                        self.f32_literals += usize::from(wrap);
                        let t = self.emit_expr(it);
                        self.f32_literals -= usize::from(wrap);
                        s.push_str(&format!("        {},\n", t?));
                    }
                    s.push_str("    );\n");
                    Ok(s)
                }
                other => Ok(format!("    var {local} = {};\n", self.emit_expr(other)?)),
            }
        })();
        self.env = saved;
        r
    }

    // ---- helpers ----

    fn push(&mut self, s: impl AsRef<str>) {
        let line = format!("{}{}", "    ".repeat(self.indent), s.as_ref());
        self.lines.push(line);
    }

    fn capture<T>(&mut self, f: impl FnOnce(&mut Self) -> Result<T>) -> Result<(T, Vec<String>)> {
        let saved = std::mem::take(&mut self.lines);
        let r = f(self);
        let got = std::mem::replace(&mut self.lines, saved);
        Ok((r?, got))
    }

    /// A WGSL name that no visible local uses. It is reserved until the scope ends.
    fn alloc_name(&mut self, source: &str) -> String {
        let base = ident(source);
        let mut e = base.clone();
        let mut i = 1;
        while self.env.name_taken(&e) {
            e = format!("{base}_{i}");
            i += 1;
        }
        self.env.declare_hidden(&e);
        e
    }

    fn declare_local(&mut self, source: &str, ty: Ty, mutable: bool) -> String {
        let emitted = self.alloc_name(source);
        self.env.declare(source, Var { ty, mutable, emitted: emitted.clone() });
        emitted
    }

    fn fresh(&mut self) -> String {
        loop {
            let name = format!("_t{}", self.tmp);
            self.tmp += 1;
            if !self.env.name_taken(&name) {
                self.env.declare_hidden(&name);
                return name;
            }
        }
    }

    fn type_of(&mut self, e: &Expr) -> Result<Ty> {
        let g = self.g;
        g.type_of(&mut self.env, e)
    }

    /// Does evaluating `e` later give the same value as evaluating it now?
    fn is_stable(&self, e: &Expr) -> bool {
        match e {
            Expr::Int(_) | Expr::Float(_) | Expr::Bool(_) => true,
            Expr::Path(n) => match self.env.lookup(n) {
                Some(v) => !v.mutable,
                None => true,
            },
            _ => false,
        }
    }

    /// Emit operands left to right. If a later operand needs statements, earlier unstable operands
    /// are copied to temporaries first, so source evaluation order is kept.
    fn emit_operands(&mut self, es: &[&Expr]) -> Result<Vec<String>> {
        let mut parts = Vec::new();
        for e in es {
            let (t, lines) = self.capture(|s| s.emit_expr(e))?;
            if t.is_empty() {
                bail!("`return`, `break` and `continue` cannot be used inside an operand");
            }
            parts.push((t, lines));
        }
        let last = parts.iter().rposition(|(_, l)| !l.is_empty());
        let mut out = Vec::new();
        for (i, ((t, lines), e)) in parts.into_iter().zip(es).enumerate() {
            self.lines.extend(lines);
            if matches!(last, Some(l) if i < l) && !self.is_stable(e) {
                let tmp = self.fresh();
                self.push(format!("let {tmp} = {t};"));
                out.push(tmp);
            } else {
                out.push(t);
            }
        }
        Ok(out)
    }

    // ---- blocks and statements ----

    fn emit_block(&mut self, b: &Block, dest: &Dest, new_scope: bool) -> Result<()> {
        if new_scope {
            self.env.push();
        }
        for s in &b.stmts {
            self.emit_stmt(s)?;
        }
        if let Some(t) = &b.tail {
            self.emit_into(t, dest)?;
        }
        if new_scope {
            self.env.pop();
        }
        Ok(())
    }

    fn needs_statements(e: &Expr) -> bool {
        matches!(e, Expr::If { select: false, .. } | Expr::Match { .. } | Expr::Block(_) | Expr::Loop(_))
    }

    fn emit_stmt(&mut self, s: &Stmt) -> Result<()> {
        match s {
            Stmt::Expr(e) => self.emit_into(e, &Dest::Discard),
            Stmt::Let { mutable, name, ty, init } => {
                let declared = ty.as_ref().map(|t| self.g.resolve_type(t)).transpose()?;
                let Some(init) = init else {
                    if !*mutable {
                        bail!("`let {name};` without a value must be `let mut {name}: T;`");
                    }
                    let Some(t) = declared else { bail!("`let mut {name};` needs a type") };
                    let emitted = self.declare_local(name, t.clone(), true);
                    let tt = self.ty_text(&t)?;
                    self.push(format!("var {emitted}: {tt};"));
                    return Ok(());
                };
                let var_ty = {
                    let it = self.type_of(init)?;
                    match &declared {
                        Some(d) if *d != it && it != Ty::Never => {
                            bail!("`{name}`: declared {}, initialiser is {}", d.describe(), it.describe())
                        }
                        Some(d) => d.clone(),
                        None => it,
                    }
                };
                if matches!(var_ty, Ty::Unit | Ty::Never) {
                    bail!("`{name}` has type {}; it cannot be bound", var_ty.describe());
                }
                let tt = self.ty_text(&var_ty)?;
                if Self::needs_statements(init) {
                    let emitted = self.alloc_name(name);
                    self.push(format!("var {emitted}: {tt};"));
                    self.emit_into(init, &Dest::Assign(emitted.clone()))?;
                    self.env.declare(name, Var { ty: var_ty, mutable: *mutable, emitted });
                } else {
                    let text = self.emit_expr(init)?;
                    if text.is_empty() {
                        bail!("`{name}` is initialised with an expression that has no value");
                    }
                    let emitted = self.declare_local(name, var_ty, *mutable);
                    let kw = if *mutable { "var" } else { "let" };
                    if declared.is_some() {
                        self.push(format!("{kw} {emitted}: {tt} = {text};"));
                    } else {
                        self.push(format!("{kw} {emitted} = {text};"));
                    }
                }
                Ok(())
            }
        }
    }

    fn emit_into(&mut self, e: &Expr, dest: &Dest) -> Result<()> {
        match e {
            Expr::Block(b) => {
                self.push("{");
                self.indent += 1;
                self.emit_block(b, dest, true)?;
                self.indent -= 1;
                self.push("}");
                Ok(())
            }
            Expr::If { select: false, cond, then, els } => {
                let c = self.emit_expr(cond)?;
                self.emit_if_rest(&c, then, els, dest)
            }
            Expr::Match { scrutinee, arms } => self.emit_match(scrutinee, arms, dest),
            Expr::Loop(b) => {
                // A function may not end in a `loop` for validators, so a valued tail loop is
                // assigned to a temporary that is returned after it.
                if matches!(dest, Dest::Return) && self.ret != Ty::Unit {
                    let ty = self.type_of(e)?;
                    if !matches!(ty, Ty::Unit | Ty::Never) {
                        let t = self.fresh();
                        let tt = self.ty_text(&ty)?;
                        self.push(format!("var {t}: {tt};"));
                        self.emit_into(e, &Dest::Assign(t.clone()))?;
                        self.push(format!("return {t};"));
                        return Ok(());
                    }
                }
                self.push("loop {");
                self.loops.push(match dest {
                    Dest::Discard => None,
                    d => Some(d.clone()),
                });
                self.indent += 1;
                self.emit_block(b, &Dest::Discard, true)?;
                self.indent -= 1;
                self.loops.pop();
                self.push("}");
                Ok(())
            }
            Expr::While { cond, body } => {
                self.indent += 1;
                let (c, lines) = self.capture(|s| s.emit_expr(cond))?;
                self.indent -= 1;
                self.loops.push(None);
                if lines.is_empty() {
                    self.push(format!("while {c} {{"));
                    self.indent += 1;
                } else {
                    self.push("loop {");
                    self.lines.extend(lines);
                    self.indent += 1;
                    self.push(format!("if !({c}) {{"));
                    self.push("    break;");
                    self.push("}");
                }
                self.emit_block(body, &Dest::Discard, true)?;
                self.indent -= 1;
                self.loops.pop();
                self.push("}");
                Ok(())
            }
            Expr::For { var, lo, hi, inclusive, body } => {
                let ty = self.type_of(lo)?;
                let texts = self.emit_operands(&[lo, hi])?;
                let hi_text = if self.is_stable(hi) {
                    texts[1].clone()
                } else {
                    let t = self.fresh();
                    self.push(format!("let {t} = {};", texts[1]));
                    t
                };
                self.env.push();
                let i = self.declare_local(var, ty, false);
                let cmp = if *inclusive { "<=" } else { "<" };
                self.push(format!("for (var {i} = {}; {i} {cmp} {hi_text}; {i}++) {{", texts[0]));
                self.loops.push(None);
                self.indent += 1;
                self.emit_block(body, &Dest::Discard, true)?;
                self.indent -= 1;
                self.loops.pop();
                self.env.pop();
                self.push("}");
                Ok(())
            }
            Expr::Return(v) => {
                match v {
                    Some(x) => {
                        let vt = self.type_of(x)?;
                        if vt != self.ret && vt != Ty::Never {
                            bail!("`return` of {}, but the function returns {}", vt.describe(), self.ret.describe());
                        }
                        if self.ret == Ty::Unit {
                            bail!("`return` with a value in a function that returns ()");
                        }
                        let t = self.emit_expr(x)?;
                        self.push(format!("return {t};"));
                    }
                    None => {
                        if self.ret != Ty::Unit {
                            bail!("`return` without a value in a function that returns {}", self.ret.describe());
                        }
                        self.push("return;");
                    }
                }
                Ok(())
            }
            Expr::Break(v) => {
                let Some(ctx) = self.loops.last().cloned() else { bail!("`break` outside of a loop") };
                match (v, ctx) {
                    (Some(x), Some(d)) => {
                        self.emit_into(x, &d)?;
                        if !matches!(d, Dest::Return) {
                            self.push("break;");
                        }
                    }
                    (Some(_), None) => bail!("`break` with a value is only allowed in a `loop` whose value is used"),
                    (None, Some(_)) => bail!("`break` in a `loop` whose value is used must carry a value"),
                    (None, None) => self.push("break;"),
                }
                Ok(())
            }
            Expr::Continue => {
                self.push("continue;");
                Ok(())
            }
            Expr::Discard => {
                self.push("discard;");
                Ok(())
            }
            _ => {
                let ty = self.type_of(e)?;
                let text = self.emit_expr(e)?;
                match dest {
                    Dest::Discard => {
                        if !text.is_empty() {
                            if ty == Ty::Unit {
                                self.push(format!("{text};"));
                            } else {
                                self.push(format!("_ = {text};"));
                            }
                        }
                    }
                    Dest::Return => {
                        if self.ret == Ty::Unit {
                            if !text.is_empty() {
                                self.push(format!("{text};"));
                            }
                        } else {
                            self.push(format!("return {text};"));
                        }
                    }
                    Dest::Assign(n) => {
                        if text.is_empty() {
                            bail!("this expression has no value");
                        }
                        self.push(format!("{n} = {text};"));
                    }
                }
                Ok(())
            }
        }
    }

    // ---- expressions ----

    fn inline_text(&mut self, e: &Expr) -> Result<String> {
        let t = self.emit_expr(e)?;
        Ok(match e {
            Expr::Int(_) | Expr::Float(_) | Expr::Bool(_) | Expr::Path(_) | Expr::Call { .. } | Expr::Field(..) | Expr::Index(..) | Expr::Cast(..) | Expr::ArrayLit(_) => t,
            _ => format!("({t})"),
        })
    }

    fn use_table(&mut self, n: &str) -> String {
        if !self.tables_used.iter().any(|x| x == n) {
            self.tables_used.push(n.to_string());
        }
        self.tables[n].clone()
    }

    /// A const is replaced by its value. Arrays that are indexed at run time stay as a local table.
    fn inline_const(&mut self, n: &str) -> Result<String> {
        let c = self.g.consts[n].clone();
        if matches!(c.ty, Ty::Array(..)) {
            return Ok(self.use_table(n));
        }
        // Const values only see other consts, never the locals of the function using them.
        let saved = std::mem::replace(&mut self.env, Env::new());
        let wrap = has_arithmetic(&c.value);
        if wrap {
            self.f32_literals += 1;
        }
        let r = self.inline_text(&c.value);
        if wrap {
            self.f32_literals -= 1;
        }
        self.env = saved;
        r
    }

    fn child_text(&self, parent: BinOp, child: &Expr, text: String, right: bool) -> String {
        if let Expr::Binary(cop, ..) = child {
            let p = parent.prec();
            let c = cop.prec();
            let paren = c < p
                || (c == p && right)
                || parent.is_bitwise()
                || cop.is_bitwise()
                || (parent.is_comparison() && cop.is_comparison())
                || matches!((parent, *cop), (BinOp::And, BinOp::Or) | (BinOp::Or, BinOp::And));
            if paren {
                return format!("({text})");
            }
        }
        text
    }

    fn postfix_base(base: &Expr, text: String) -> String {
        if matches!(base, Expr::Binary(..) | Expr::Unary(..)) { format!("({text})") } else { text }
    }

    fn emit_expr(&mut self, e: &Expr) -> Result<String> {
        match e {
            Expr::Int(s) => Ok(int_text(s)),
            Expr::Float(s) if self.f32_literals > 0 => Ok(format!("f32({})", float_text(s))),
            Expr::Float(s) => Ok(float_text(s)),
            Expr::Bool(b) => Ok(b.to_string()),
            Expr::Path(n) => {
                if let Some(v) = self.env.lookup(n) {
                    Ok(v.emitted.clone())
                } else if self.g.consts.contains_key(n) {
                    self.inline_const(n)
                } else if self.g.resources.contains_key(n) {
                    Ok(ident(n))
                } else {
                    bail!("unknown name `{n}`")
                }
            }
            Expr::Unary(op, x) => {
                let t = self.emit_expr(x)?;
                let t = if matches!(**x, Expr::Binary(..) | Expr::Unary(..)) { format!("({t})") } else { t };
                Ok(format!("{}{t}", op.text()))
            }
            Expr::Binary(op @ (BinOp::And | BinOp::Or), l, r) => self.emit_logical(*op, l, r),
            Expr::Binary(op, l, r) => {
                let t = self.emit_operands(&[l, r])?;
                let lt = self.child_text(*op, l, t[0].clone(), false);
                let rt = self.child_text(*op, r, t[1].clone(), true);
                Ok(format!("{lt} {} {rt}", op.text()))
            }
            Expr::Assign { op, target, value } => {
                self.emit_assign(*op, target, value)?;
                Ok(String::new())
            }
            Expr::Call { name, generics, args } => self.emit_call(e, name, generics, args),
            Expr::Method { recv, name, args } => {
                let mut es: Vec<&Expr> = vec![recv];
                es.extend(args.iter());
                let t = self.emit_operands(&es)?;
                let f = match (name.as_str(), t.len()) {
                    ("sample", 3) => "textureSample",
                    ("sample_level", 4) => "textureSampleLevel",
                    ("load", 3) => "textureLoad",
                    ("size", 1) => "textureDimensions",
                    _ => bail!("`.{name}(..)` called with the wrong number of arguments"),
                };
                Ok(format!("{f}({})", t.join(", ")))
            }
            Expr::Field(base, f) => {
                let bt = self.type_of(base)?;
                let t = self.emit_expr(base)?;
                let t = Self::postfix_base(base, t);
                match bt {
                    Ty::Vec(..) => Ok(format!("{t}.{f}")),
                    _ => Ok(format!("{t}.{}", ident(f))),
                }
            }
            Expr::Index(base, idx) => {
                if let Expr::Path(n) = &**base {
                    if self.env.lookup(n).is_none() && self.g.consts.get(n).is_some_and(|c| matches!(c.ty, Ty::Array(..))) {
                        let c = self.g.consts[n].clone();
                        if let (Some(i), Expr::ArrayLit(items)) = (self.g.const_int(idx), &c.value) {
                            let Some(item) = usize::try_from(i).ok().and_then(|i| items.get(i)) else {
                                bail!("index {i} is out of range for const `{n}` ({} elements)", items.len());
                            };
                            let saved = std::mem::replace(&mut self.env, Env::new());
                            let wrap = has_arithmetic(item);
                            self.f32_literals += usize::from(wrap);
                            let r = self.inline_text(item);
                            self.f32_literals -= usize::from(wrap);
                            self.env = saved;
                            return r;
                        }
                        let table = self.use_table(n);
                        let t = self.emit_operands(&[idx])?;
                        return Ok(format!("{table}[{}]", t[0]));
                    }
                }
                let t = self.emit_operands(&[base, idx])?;
                Ok(format!("{}[{}]", Self::postfix_base(base, t[0].clone()), t[1]))
            }
            Expr::Cast(x, to) => {
                let to = self.g.resolve_type(to)?;
                let t = self.emit_expr(x)?;
                Ok(format!("{}({t})", self.ty_text(&to)?))
            }
            Expr::StructLit { name, fields, base } => self.emit_struct_lit(name, fields, base),
            Expr::ArrayLit(items) => {
                let ty = self.type_of(e)?;
                let refs: Vec<&Expr> = items.iter().collect();
                let t = self.emit_operands(&refs)?;
                Ok(format!("{}({})", self.ty_text(&ty)?, t.join(", ")))
            }
            Expr::If { select: true, cond, then, els } => self.emit_select(cond, then, els),
            Expr::Block(_) | Expr::If { .. } | Expr::Match { .. } | Expr::Loop(_) => {
                let ty = self.type_of(e)?;
                if matches!(ty, Ty::Unit | Ty::Never) {
                    self.emit_into(e, &Dest::Discard)?;
                    return Ok(String::new());
                }
                let t = self.fresh();
                let tt = self.ty_text(&ty)?;
                self.push(format!("var {t}: {tt};"));
                self.emit_into(e, &Dest::Assign(t.clone()))?;
                Ok(t)
            }
            Expr::While { .. } | Expr::For { .. } | Expr::Return(_) | Expr::Break(_) | Expr::Continue | Expr::Discard => {
                self.emit_into(e, &Dest::Discard)?;
                Ok(String::new())
            }
        }
    }

    fn emit_logical(&mut self, op: BinOp, l: &Expr, r: &Expr) -> Result<String> {
        let lt = self.emit_expr(l)?;
        self.indent += 1;
        let (rt, rlines) = self.capture(|s| s.emit_expr(r))?;
        self.indent -= 1;
        if rlines.is_empty() {
            let lt = self.child_text(op, l, lt, false);
            let rt = self.child_text(op, r, rt, true);
            return Ok(format!("{lt} {} {rt}", op.text()));
        }
        // The right side needs statements, so it may only run when the left side allows it.
        let tmp = self.fresh();
        self.push(format!("var {tmp} = {lt};"));
        self.push(if op == BinOp::And { format!("if {tmp} {{") } else { format!("if !{tmp} {{") });
        self.lines.extend(rlines);
        self.indent += 1;
        self.push(format!("{tmp} = {rt};"));
        self.indent -= 1;
        self.push("}");
        Ok(tmp)
    }

    fn is_trivial(&self, e: &Expr) -> bool {
        match e {
            Expr::Int(_) | Expr::Float(_) | Expr::Bool(_) | Expr::Path(_) => true,
            Expr::Unary(_, x) | Expr::Field(x, _) | Expr::Cast(x, _) => self.is_trivial(x),
            Expr::Binary(_, a, b) | Expr::Index(a, b) => self.is_trivial(a) && self.is_trivial(b),
            Expr::Call { name, args, .. } => {
                let callable = if self.g.fns.contains_key(name) {
                    crate::emit::common::is_pure_fn(self.p, name)
                } else {
                    is_intrinsic(name) || is_constructor(name)
                };
                callable && args.iter().all(|a| self.is_trivial(a))
            }
            _ => false,
        }
    }

    fn emit_select(&mut self, cond: &Expr, then: &Block, els: &Option<Box<Expr>>) -> Result<String> {
        let arm = |b: &Block| -> Option<Expr> {
            if b.stmts.is_empty() { b.tail.as_deref().cloned() } else { None }
        };
        let (Some(t), Some(Expr::Block(eb))) = (arm(then), els.as_deref()) else {
            bail!("`#[select]` needs `if c {{ a }} else {{ b }}` with plain value arms");
        };
        let Some(f) = arm(eb) else { bail!("`#[select]` needs `if c {{ a }} else {{ b }}` with plain value arms") };
        if !self.is_trivial(&t) || !self.is_trivial(&f) {
            bail!("`#[select]` arms must be trivial expressions (no blocks or control flow, and only calls to pure functions); `select` evaluates both arms");
        }
        let texts = self.emit_operands(&[&f, &t, cond])?;
        Ok(format!("select({}, {}, {})", texts[0], texts[1], texts[2]))
    }

    fn emit_call(&mut self, call: &Expr, name: &str, generics: &[Type], args: &[Expr]) -> Result<String> {
        let refs: Vec<&Expr> = args.iter().collect();
        if self.g.fns.contains_key(name) {
            let t = self.emit_operands(&refs)?;
            return Ok(format!("{}({})", ident(name), t.join(", ")));
        }
        let t = self.emit_operands(&refs)?;
        let callee = match name {
            "f32" | "i32" | "u32" | "bool" => name.to_string(),
            "vec2" | "vec3" | "vec4" | "mat2" | "mat3" | "mat4" => {
                let ty = self.type_of(call)?;
                let full = self.ty_text(&ty)?;
                full
            }
            "bitcast" => {
                let Some(g) = generics.first() else { bail!("`bitcast` needs a target type") };
                format!("bitcast<{}>", self.ty_text(&self.g.resolve_type(g)?)?)
            }
            n if is_intrinsic(n) => n.to_string(),
            n => bail!("unknown function `{n}`"),
        };
        Ok(format!("{callee}({})", t.join(", ")))
    }

    fn emit_struct_lit(&mut self, name: &str, fields: &[(String, Expr)], base: &Option<Box<Expr>>) -> Result<String> {
        let decl = self.g.structs[name].clone();
        let refs: Vec<&Expr> = fields.iter().map(|(_, v)| v).collect();
        let texts = self.emit_operands(&refs)?;
        let base_text = match base {
            Some(b) => {
                let t = self.emit_expr(b)?;
                if matches!(**b, Expr::Path(_)) {
                    Some(t)
                } else {
                    let tmp = self.fresh();
                    self.push(format!("let {tmp} = {t};"));
                    Some(tmp)
                }
            }
            None => None,
        };
        let mut parts = Vec::new();
        for f in &decl {
            if let Some(i) = fields.iter().position(|(n, _)| *n == f.name) {
                parts.push(texts[i].clone());
            } else if let Some(b) = &base_text {
                parts.push(format!("{b}.{}", ident(&f.name)));
            } else {
                bail!("struct literal `{name}` is missing field `{}`", f.name);
            }
        }
        Ok(format!("{}({})", ident(name), parts.join(", ")))
    }
}
