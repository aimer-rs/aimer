fn validate_range(
    field: &'static str,
    value: u64,
    minimum: u64,
    maximum: u64,
) -> Result<(), DevelopmentHostConfigError> {
    if !(minimum..=maximum).contains(&value) {
        return Err(DevelopmentHostConfigError::OutOfRange {
            field,
            value,
            minimum,
            maximum,
        });
    }
    Ok(())
}

fn validate_not_greater(
    field: &'static str,
    value: u64,
    maximum_field: &'static str,
    maximum: u64,
) -> Result<(), DevelopmentHostConfigError> {
    if value > maximum {
        return Err(DevelopmentHostConfigError::ExceedsField {
            field,
            maximum_field,
        });
    }
    Ok(())
}

/// Failure while parsing, validating, or serializing host configuration text.
///
/// Unknown field names and malformed line contents are intentionally omitted
/// from error values so diagnostics cannot echo a mistakenly supplied secret.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum DevelopmentHostConfigError {
    /// Input exceeded [`MAX_DEVELOPMENT_HOST_CONFIG_TEXT_BYTES`].
    TextTooLong { actual: usize, maximum: usize },
    /// A line was empty or was not exactly one key/value record.
    MalformedLine,
    /// A format version is not supported by this implementation.
    UnsupportedVersion(u64),
    /// A required field was absent.
    MissingField(&'static str),
    /// A field occurred more than once.
    DuplicateField(&'static str),
    /// A key is not part of the current format.
    UnknownField,
    /// A known field was not an unsigned decimal integer.
    MalformedValue(&'static str),
    /// A value was outside its inclusive safety range.
    OutOfRange {
        field: &'static str,
        value: u64,
        minimum: u64,
        maximum: u64,
    },
    /// A ceiling exceeded another ceiling that contains it.
    ExceedsField {
        field: &'static str,
        maximum_field: &'static str,
    },
}

impl fmt::Display for DevelopmentHostConfigError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::TextTooLong { actual, maximum } => write!(
                formatter,
                "development host configuration is {actual} bytes but the limit is {maximum}"
            ),
            Self::MalformedLine => {
                formatter.write_str("development host configuration contains a malformed line")
            }
            Self::UnsupportedVersion(version) => {
                write!(
                    formatter,
                    "unsupported development host configuration version {version}"
                )
            }
            Self::MissingField(field) => write!(
                formatter,
                "development host configuration is missing field {field}"
            ),
            Self::DuplicateField(field) => write!(
                formatter,
                "development host configuration repeats field {field}"
            ),
            Self::UnknownField => {
                formatter.write_str("development host configuration contains an unknown field")
            }
            Self::MalformedValue(field) => write!(
                formatter,
                "development host configuration field {field} is malformed"
            ),
            Self::OutOfRange {
                field,
                value,
                minimum,
                maximum,
            } => write!(
                formatter,
                "development host configuration field {field} is {value}, outside {minimum}..={maximum}"
            ),
            Self::ExceedsField {
                field,
                maximum_field,
            } => write!(
                formatter,
                "development host configuration field {field} exceeds {maximum_field}"
            ),
        }
    }
}

impl Error for DevelopmentHostConfigError {}

impl FromStr for DevelopmentHostConfig {
    type Err = DevelopmentHostConfigError;

    fn from_str(text: &str) -> Result<Self, Self::Err> {
        Self::from_text(text)
    }
}

fn parse_config(text: &str) -> Result<DevelopmentHostConfig, DevelopmentHostConfigError> {
    if text.len() > MAX_DEVELOPMENT_HOST_CONFIG_TEXT_BYTES {
        return Err(DevelopmentHostConfigError::TextTooLong {
            actual: text.len(),
            maximum: MAX_DEVELOPMENT_HOST_CONFIG_TEXT_BYTES,
        });
    }

    let mut values = ParsedValues::new();
    for line in text.lines() {
        if line.is_empty() {
            return Err(DevelopmentHostConfigError::MalformedLine);
        }
        let Some((key, value)) = line.split_once('=') else {
            return Err(DevelopmentHostConfigError::MalformedLine);
        };
        if key.is_empty() || value.is_empty() || value.contains('=') {
            return Err(DevelopmentHostConfigError::MalformedLine);
        }
        values.set(key, value)?;
    }
    values.finish()
}

