/// Version of the canonical development-host configuration text format.
pub const DEVELOPMENT_HOST_CONFIG_VERSION: u64 = 1;

/// Largest development-host configuration accepted by the parser, in bytes.
///
/// The limit is applied before lines or values are inspected. It keeps private
/// environment variables and app-private session files from becoming an
/// unbounded parsing or allocation input.
pub const MAX_DEVELOPMENT_HOST_CONFIG_TEXT_BYTES: usize = 4_096;

const MAX_FUEL: u64 = 1_000_000_000;
const MAX_MODULE_BYTES: u64 = 256 * 1_024 * 1_024;
const MAX_MEMORY_PAGES: u64 = 65_536;
const MAX_TABLE_ELEMENTS: u64 = 1_000_000;
const MAX_CALL_DEPTH: u64 = 65_536;
const MAX_CHUNK_BYTES: u64 = 16 * 1_024 * 1_024;
const MAX_DIAGNOSTIC_BYTES: u64 = 1_024 * 1_024;
const MAX_TERMINAL_RESULTS: u64 = 1_024;
const MAX_IO_TIMEOUT_MS: u64 = 300_000;
const MAX_CREDENTIAL_TTL_MS: u64 = 86_400_000;
const MAX_AUTHENTICATION_FAILURES: u64 = 1_024;
const MAX_AUTHENTICATION_BACKOFF_MS: u64 = 60_000;
const MAX_MODEL_DOCUMENT_BYTES: u64 = 64 * 1_024 * 1_024;
const MAX_MODEL_ITEMS: u64 = 1_000_000;
const MAX_MODEL_PROPERTIES: u64 = 4_000_000;
const MAX_WIDGET_DEPTH: u64 = 4_096;
const MAX_RETIRED_GENERATIONS: u64 = 1_024;
const MAX_CALLBACK_BINDINGS: u64 = 1_000_000;
const MAX_QUEUE_CAPACITY: u64 = 65_536;

/// Secret-free resource policy used to construct a development reload host.
///
/// This value contains only primitive execution, transport, authentication
/// defense, model, generation, state-transfer, and queue ceilings. It never
/// contains a session identifier or authentication token. Use
/// [`Self::cli_safe_profile`] when the CLI needs the explicit built-in profile;
/// this type deliberately does not implement [`Default`].
///
/// Profiles can be transported as bounded canonical text with [`Self::to_text`]
/// and parsed with [`str::parse`]. Every field is required while parsing, and
/// serialization validates programmatic builder changes before producing text.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct DevelopmentHostConfig {
    widget_ir_diagnostics: bool,
    runtime_fuel_per_call: u64,
    max_module_bytes: usize,
    runtime_max_memory_pages: u32,
    runtime_max_table_elements: u32,
    runtime_max_call_depth: u32,
    protocol_max_chunk_bytes: usize,
    protocol_max_diagnostic_bytes: usize,
    protocol_max_terminal_results: usize,
    protocol_io_timeout_ms: u64,
    listener_credential_ttl_ms: u64,
    listener_max_authentication_failures: u32,
    listener_authentication_backoff_ms: u64,
    model_max_document_bytes: usize,
    model_max_state_entries: u32,
    model_max_widget_nodes: u32,
    model_max_properties: u32,
    model_max_widget_depth: u32,
    generation_max_retired: usize,
    max_callback_bindings: u32,
    state_transfer_migration_fuel: u64,
    reload_command_queue_capacity: usize,
    event_queue_capacity: usize,
}

macro_rules! config_accessors {
    ($( $setter:ident => $getter:ident: $ty:ty => $doc:literal, )+) => {
        $(
            #[doc = $doc]
            #[inline]
            pub const fn $setter(mut self, value: $ty) -> Self {
                self.$setter = value;
                self
            }

            #[doc = concat!("Returns the value configured by [`Self::", stringify!($setter), "`].")]
            #[inline]
            pub const fn $getter(self) -> $ty {
                self.$setter
            }
        )+
    };
}

